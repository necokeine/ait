//! Workspace execution and Git commit coverage for the Codex adapter.

use std::{process::Command, sync::Arc};

use ait_agent_adapters::{
    AdapterError, AgentAdapter, AgentCapabilities, AgentEvent, AgentRunRequest, AgentRunStatus,
    AgentStream, SandboxMode,
    codex::{CodexSessionTitleGenerator, CodexWorkspaceAgent},
};
use ait_ports::{
    SessionTitleGenerator, SessionTitleRequest, WorkspaceAgent, WorkspaceAgentInvocation,
    WorkspaceOutputItem,
};
use async_trait::async_trait;
use serde_json::json;
use tempfile::TempDir;
use tokio_util::sync::CancellationToken;

#[derive(Debug)]
struct EditingAdapter;

#[async_trait]
impl AgentAdapter for EditingAdapter {
    fn driver(&self) -> &'static str {
        "editing_test"
    }

    fn capabilities(&self) -> AgentCapabilities {
        AgentCapabilities {
            streaming: true,
            thread_resume: false,
            approvals: false,
            command_execution: true,
            file_changes: true,
            usage: false,
        }
    }

    async fn run(&self, request: AgentRunRequest) -> Result<AgentStream, AdapterError> {
        assert_eq!(
            request.project_instructions.as_deref(),
            Some("Keep generated files small.")
        );
        std::fs::write(request.cwd.join("answer.txt"), "generated by codex\n").unwrap();
        Ok(Box::pin(tokio_stream::iter([
            Ok(AgentEvent::ItemStarted {
                item: json!({
                    "type": "agentMessage",
                    "id": "commentary-1",
                    "phase": "commentary",
                    "text": ""
                }),
            }),
            Ok(AgentEvent::MessageDelta {
                item_id: "commentary-1".into(),
                delta: "Inspecting the ".into(),
            }),
            Ok(AgentEvent::ItemCompleted {
                item: json!({
                    "type": "agentMessage",
                    "id": "commentary-1",
                    "phase": "commentary",
                    "text": "Inspecting the repository."
                }),
            }),
            Ok(AgentEvent::ItemStarted {
                item: json!({
                    "type": "commandExecution",
                    "id": "command-1",
                    "status": "inProgress"
                }),
            }),
            Ok(AgentEvent::ItemCompleted {
                item: json!({
                    "type": "commandExecution",
                    "id": "command-1",
                    "command": "sed -n '1,20p' src/main.rs",
                    "cwd": "/workspace",
                    "status": "completed",
                    "commandActions": [{
                        "type": "read",
                        "command": "sed -n '1,20p' src/main.rs",
                        "name": "main.rs",
                        "path": "src/main.rs"
                    }],
                    "aggregatedOutput": "fn main() {}",
                    "exitCode": 0
                }),
            }),
            Ok(AgentEvent::ItemCompleted {
                item: json!({
                    "type": "agentMessage",
                    "id": "commentary-2",
                    "phase": "commentary",
                    "text": "The relevant file is small."
                }),
            }),
            Ok(AgentEvent::ItemStarted {
                item: json!({
                    "type": "agentMessage",
                    "id": "final-1",
                    "phase": "final_answer",
                    "text": ""
                }),
            }),
            Ok(AgentEvent::MessageDelta {
                item_id: "final-1".into(),
                delta: "Implemented the requested ".into(),
            }),
            Ok(AgentEvent::ItemCompleted {
                item: json!({
                    "type": "agentMessage",
                    "id": "final-1",
                    "phase": "final_answer",
                    "text": "Implemented the requested change."
                }),
            }),
            Ok(AgentEvent::Completed {
                turn_id: "turn-1".into(),
                status: AgentRunStatus::Completed,
                error: None,
            }),
        ])))
    }
}

#[derive(Debug)]
struct TitleAdapter;

#[async_trait]
impl AgentAdapter for TitleAdapter {
    fn driver(&self) -> &'static str {
        "title_test"
    }

    fn capabilities(&self) -> AgentCapabilities {
        AgentCapabilities {
            streaming: true,
            thread_resume: false,
            approvals: false,
            command_execution: false,
            file_changes: false,
            usage: false,
        }
    }

    async fn run(&self, request: AgentRunRequest) -> Result<AgentStream, AdapterError> {
        assert_eq!(request.model.as_deref(), Some("gpt-5.6-luna"));
        assert_eq!(request.reasoning_effort.as_deref(), Some("low"));
        assert_eq!(request.sandbox, SandboxMode::ReadOnly);
        assert_eq!(
            request.output_schema.as_ref().unwrap()["required"][0],
            "title"
        );
        assert!(request.prompt.contains("ABC-123"));
        Ok(Box::pin(tokio_stream::iter([
            Ok(AgentEvent::MessageDelta {
                item_id: "message-title".into(),
                delta: r#"{"title":"修复 ABC-123 登录","description":"修复登录流程中的工单问题"}"#
                    .into(),
            }),
            Ok(AgentEvent::Completed {
                turn_id: "turn-title".into(),
                status: AgentRunStatus::Completed,
                error: None,
            }),
        ])))
    }
}

#[tokio::test]
async fn generates_structured_session_metadata_with_the_small_read_only_model() {
    let project = TempDir::new().unwrap();
    let generator = CodexSessionTitleGenerator::new(Arc::new(TitleAdapter));
    let generated = generator
        .generate(SessionTitleRequest {
            request_id: "title-1".into(),
            user_prompt: "修复 ABC-123 登录".into(),
            cwd: project.path().to_path_buf(),
            cancellation: CancellationToken::new(),
        })
        .await
        .unwrap();

    assert_eq!(generated.title, "修复 ABC-123 登录");
    assert_eq!(generated.description, "修复登录流程中的工单问题");
}

#[tokio::test]
async fn returns_assistant_result_and_commits_generated_changes() {
    let project = TempDir::new().unwrap();
    assert!(
        Command::new("git")
            .arg("-C")
            .arg(project.path())
            .arg("init")
            .status()
            .unwrap()
            .success()
    );
    let agent = CodexWorkspaceAgent::new(Arc::new(EditingAdapter));
    let result = agent
        .invoke(WorkspaceAgentInvocation {
            request_id: "run-1".into(),
            model: "test-model".into(),
            reasoning_effort: Some("high".into()),
            prompt: "Create answer.txt".into(),
            project_instructions: Some("Keep generated files small.".into()),
            commit_subject: "Create the generated answer".into(),
            cwd: project.path().to_path_buf(),
            cancellation: CancellationToken::new(),
        })
        .await
        .unwrap();

    assert_eq!(result.assistant_text, "Implemented the requested change.");
    assert!(result.commit_id.is_some());
    assert_eq!(result.operations.len(), 1);
    assert_eq!(result.operations[0].kind, "read");
    assert_eq!(result.operations[0].title, "Read file");
    assert_eq!(result.operations[0].paths, ["src/main.rs"]);
    assert!(
        result.operations[0]
            .detail
            .as_deref()
            .unwrap()
            .contains("fn main() {}")
    );
    assert_eq!(
        result.output_items,
        [
            WorkspaceOutputItem::Message {
                id: "commentary-1".into(),
                phase: Some("commentary".into()),
                text: "Inspecting the repository.".into(),
            },
            WorkspaceOutputItem::Operation {
                id: "command-1".into(),
            },
            WorkspaceOutputItem::Message {
                id: "commentary-2".into(),
                phase: Some("commentary".into()),
                text: "The relevant file is small.".into(),
            },
            WorkspaceOutputItem::Message {
                id: "final-1".into(),
                phase: Some("final_answer".into()),
                text: "Implemented the requested change.".into(),
            },
        ]
    );
    let subject = Command::new("git")
        .arg("-C")
        .arg(project.path())
        .args(["log", "-1", "--pretty=%s"])
        .output()
        .unwrap();
    assert_eq!(
        String::from_utf8_lossy(&subject.stdout).trim(),
        "ait: Create the generated answer"
    );
    assert_eq!(
        std::fs::read_to_string(project.path().join("answer.txt")).unwrap(),
        "generated by codex\n"
    );
    let status = Command::new("git")
        .arg("-C")
        .arg(project.path())
        .args(["status", "--porcelain=v1"])
        .output()
        .unwrap();
    assert!(status.stdout.is_empty());
}

#[tokio::test]
async fn refuses_to_mix_existing_user_changes_into_codex_commit() {
    let project = TempDir::new().unwrap();
    Command::new("git")
        .arg("-C")
        .arg(project.path())
        .arg("init")
        .status()
        .unwrap();
    std::fs::write(project.path().join("user-work.txt"), "keep me\n").unwrap();
    let agent = CodexWorkspaceAgent::new(Arc::new(EditingAdapter));
    let error = agent
        .invoke(WorkspaceAgentInvocation {
            request_id: "run-2".into(),
            model: "test-model".into(),
            reasoning_effort: None,
            prompt: "Change something".into(),
            project_instructions: None,
            commit_subject: "Change something".into(),
            cwd: project.path().to_path_buf(),
            cancellation: CancellationToken::new(),
        })
        .await
        .unwrap_err();

    assert_eq!(error.code, ait_domain::ErrorCode::InvalidConfiguration);
    assert!(!project.path().join("answer.txt").exists());
}
