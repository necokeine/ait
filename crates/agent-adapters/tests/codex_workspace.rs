#[derive(Debug)]
struct ScriptedAdapter {
    events: Vec<AgentEvent>,
}

#[derive(Default)]
struct RecordingProgress(Mutex<Vec<WorkspaceProgressEvent>>);

#[async_trait]
impl WorkspaceProgressReporter for RecordingProgress {
    async fn report(&self, event: WorkspaceProgressEvent) {
        self.0.lock().unwrap().push(event);
    }
}

#[derive(Clone, Copy, Debug)]
enum FaultEnding {
    Failed,
    Eof,
    StreamError,
}

#[derive(Debug)]
struct FaultingAdapter(FaultEnding);

#[async_trait]
impl AgentAdapter for FaultingAdapter {
    fn driver(&self) -> &'static str {
        "faulting_test"
    }

    fn capabilities(&self) -> AgentCapabilities {
        AgentCapabilities {
            streaming: true,
            thread_resume: false,
            approvals: false,
            command_execution: true,
            file_changes: true,
            usage: false,
        }
    }

    async fn run(&self, request: AgentRunRequest) -> Result<AgentStream, AdapterError> {
        std::fs::write(request.cwd.join("retained.txt"), "retained\n").unwrap();
        let mut events = vec![
            Ok(AgentEvent::ItemCompleted {
                item: json!({
                    "type": "agentMessage",
                    "id": "confirmed-commentary",
                    "phase": "commentary",
                    "text": "Confirmed before failure."
                }),
            }),
            Ok(AgentEvent::ItemCompleted {
                item: json!({
                    "type": "fileChange",
                    "id": "confirmed-change",
                    "status": "completed",
                    "changes": [{"path": "retained.txt", "kind": "add"}]
                }),
            }),
            Ok(AgentEvent::MessageDelta {
                item_id: "unfinished-final".into(),
                delta: "Unfinished answer".into(),
            }),
        ];
        match self.0 {
            FaultEnding::Failed => events.push(Ok(AgentEvent::Completed {
                turn_id: "failed-turn".into(),
                status: AgentRunStatus::Failed,
                error: Some("injected failure".into()),
            })),
            FaultEnding::Eof => {}
            FaultEnding::StreamError => events.push(Err(AdapterError::new(
                ait_agent_adapters::AdapterErrorKind::ProcessExited,
                "injected stream error",
                true,
            ))),
        }
        Ok(Box::pin(tokio_stream::iter(events)))
    }
}

#[async_trait]
impl AgentAdapter for ScriptedAdapter {
    fn driver(&self) -> &'static str {
        "scripted_test"
    }

    fn capabilities(&self) -> AgentCapabilities {
        AgentCapabilities {
            streaming: true,
            thread_resume: false,
            approvals: false,
            command_execution: false,
            file_changes: false,
            usage: false,
        }
    }

    async fn run(&self, _: AgentRunRequest) -> Result<AgentStream, AdapterError> {
        Ok(Box::pin(tokio_stream::iter(
            self.events.clone().into_iter().map(Ok),
        )))
    }
}

fn initialized_project() -> TempDir {
    let project = TempDir::new().unwrap();
    assert!(
        Command::new("git")
            .arg("-C")
            .arg(project.path())
            .arg("init")
            .status()
            .unwrap()
            .success()
    );
    project
}

async fn invoke_script(events: Vec<AgentEvent>) -> ait_ports::WorkspaceAgentResponse {
    let project = initialized_project();
    CodexWorkspaceAgent::new(Arc::new(ScriptedAdapter { events }))
        .invoke(WorkspaceAgentInvocation {
            request_id: "scripted-run".into(),
            model: "test-model".into(),
            reasoning_effort: None,
            prompt: "Return a result".into(),
            project_instructions: None,
            commit_subject: "Return a result".into(),
            cwd: project.path().to_path_buf(),
            adopted_worktree_fingerprint: None,
            cancellation: CancellationToken::new(),
        })
        .await
        .unwrap()
}

